"""Generates the voice lines for the "Let me check" ad with Kokoro-82M (offline TTS).

Reads src/call/script.json, writes one WAV per line to public/call/vo/ and the
durations plus word timings to src/call/vo.ts. The WAVs and vo.ts are
committed, so rendering the video doesn't need this script or the model.

    python -I scripts/make-voice.py --model kokoro-q8.onnx --voices voices.npz

Model: Kokoro-82M v1.0 ONNX, q8 (onnx-community/Kokoro-82M-v1.0-ONNX,
model_quantized.onnx, sha256 fbae9257...a1478). voices.npz holds the voice
style arrays (510x1x256 float32 per voice) keyed by name, as shipped in the
kokoro-js npm package. Requires `pip install kokoro-onnx==0.6.1 soundfile`.

The model reports no durations, so word timings are estimated: speech runs
are found from the audio energy, words are grouped at punctuation (where the
model pauses), and inside a run each word gets time in proportion to its
phoneme count.
"""

import argparse
import json
import pathlib
import re

import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro

ROOT = pathlib.Path(__file__).resolve().parent.parent
SR = 24000
HOP = 240  # 10 ms


def speech_runs(audio: np.ndarray) -> list[tuple[float, float]]:
    """Spans (s) where the voice is active; gaps under 140 ms are bridged."""
    frames = len(audio) // HOP
    rms = np.array([np.sqrt(np.mean(audio[i * HOP:(i + 1) * HOP] ** 2) + 1e-12) for i in range(frames)])
    thresh = rms.max() * 10 ** (-38 / 20)
    active = rms > thresh
    runs, start = [], None
    for i, a in enumerate(active):
        if a and start is None:
            start = i
        if not a and start is not None:
            runs.append([start, i])
            start = None
    if start is not None:
        runs.append([start, frames])
    merged = []
    for r in runs:
        if merged and r[0] - merged[-1][1] < 14:
            merged[-1][1] = r[1]
        else:
            merged.append(r)
    merged = [r for r in merged if r[1] - r[0] >= 4]
    return [(r[0] * HOP / SR, r[1] * HOP / SR) for r in merged]


def word_timings(kokoro: Kokoro, text: str, audio: np.ndarray) -> list[dict]:
    words = text.split()
    weights = []
    for w in words:
        bare = re.sub(r"[^\w']", "", w)
        ph = kokoro.tokenizer.phonemize(bare) if bare else ""
        weights.append(max(1, len(ph.replace(" ", ""))))
    # Phrase groups end at punctuation, where the model leaves a pause.
    groups, cur = [], []
    for i, w in enumerate(words):
        cur.append(i)
        if re.search(r"[.,!?;:]\W*$", w) or w.endswith("..."):
            groups.append(cur)
            cur = []
    if cur:
        groups.append(cur)

    runs = speech_runs(audio)
    if len(runs) != len(groups):
        # Fall back to one span from first onset to last offset.
        runs = [(runs[0][0], runs[-1][1])]
        groups = [list(range(len(words)))]

    out = []
    for (s, e), g in zip(runs, groups):
        total = sum(weights[i] for i in g)
        t = s
        for i in g:
            d = (e - s) * weights[i] / total
            out.append({"word": words[i], "start": round(t, 3), "end": round(t + d, 3)})
            t += d
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", required=True)
    ap.add_argument("--voices", required=True)
    args = ap.parse_args()

    script = json.loads((ROOT / "src" / "call" / "script.json").read_text())
    kokoro = Kokoro(args.model, args.voices)
    out_dir = ROOT / "public" / "call" / "vo"
    out_dir.mkdir(parents=True, exist_ok=True)

    manifest = {}
    for line in script["lines"]:
        cast = script["voices"][line["speaker"]]
        audio, sr = kokoro.create(line["text"], voice=cast["voice"], speed=cast["speed"], lang="en-us")
        assert sr == SR
        audio = audio.astype(np.float32)
        peak = float(np.abs(audio).max())
        audio = audio / peak * 0.89  # -1 dBFS; the mix sets the final level
        sf.write(out_dir / f"{line['id']}.wav", audio, SR, subtype="PCM_16")
        words = word_timings(kokoro, line["text"], audio)
        manifest[line["id"]] = {
            "speaker": line["speaker"],
            "text": line["text"],
            "duration": round(len(audio) / SR, 3),
            "words": words,
        }
        print(f"{line['id']:12s} {len(audio) / SR:5.2f}s  {line['text']}")

    (ROOT / "src" / "call" / "vo.ts").write_text(
        "// Generated by scripts/make-voice.py. Do not edit by hand.\n"
        "export const VO = " + json.dumps(manifest, indent=1) + " as const;\n\n"
        "export type LineId = keyof typeof VO;\n"
    )
    total = sum(m["duration"] for m in manifest.values())
    print(f"{len(manifest)} lines, {total:.1f}s of speech")


if __name__ == "__main__":
    main()
